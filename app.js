// =====================================================
// فحص الفوز
//
// الأزرق:
// الاتصال من اليسار إلى اليمين
//
// الأحمر:
// الاتصال من الأعلى إلى الأسفل
// =====================================================

function checkLettersWinner(team) {

    const size = 5;


    const visited =
        new Set();


    const queue = [];


    if (team === "blue") {

        for (
            let row = 0;
            row < size;
            row++
        ) {

            const index =
                row * size;


            if (
                lettersGameBoard[index].owner ===
                "blue"
            ) {

                queue.push(index);

                visited.add(index);

            }

        }

    }


    else {

        for (
            let column = 0;
            column < size;
            column++
        ) {

            const index =
                column;


            if (
                lettersGameBoard[index].owner ===
                "red"
            ) {

                queue.push(index);

                visited.add(index);

            }

        }

    }


    while (
        queue.length > 0
    ) {

        const current =
            queue.shift();


        const row =
            Math.floor(
                current / size
            );


        const column =
            current % size;


        if (
            team === "blue" &&
            column === size - 1
        ) {

            return "blue";

        }


        if (
            team === "red" &&
            row === size - 1
        ) {

            return "red";

        }


        const neighbors = [

            [row - 1, column],

            [row + 1, column],

            [row, column - 1],

            [row, column + 1]

        ];


        neighbors.forEach(
            function(position) {

                const newRow =
                    position[0];


                const newColumn =
                    position[1];


                if (
                    newRow < 0 ||
                    newRow >= size ||
                    newColumn < 0 ||
                    newColumn >= size
                ) {

                    return;

                }


                const nextIndex =
                    newRow * size +
                    newColumn;


                if (
                    visited.has(nextIndex)
                ) {

                    return;

                }


                if (
                    lettersGameBoard[
                        nextIndex
                    ].owner !== team
                ) {

                    return;

                }


                visited.add(
                    nextIndex
                );


                queue.push(
                    nextIndex
                );

            }
        );

    }


    return null;
}


