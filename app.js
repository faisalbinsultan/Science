// =====================================================
// عرض سؤال الاختبار
// =====================================================

function showQuestion() {

    const content =
        document.getElementById("quizContent");


    if (!content) {
        return;
    }


    if (
        currentQuestion >=
        currentQuiz.length
    ) {

        showResult();

        return;
    }


    const question =
        currentQuiz[currentQuestion];


    let options = "";


    question.options.forEach(
        function(option, index) {

            options += `

                <button
                    class="quiz-option"
                    onclick="answerQuestion(${index})">

                    <span class="option-number">
                        ${index + 1}
                    </span>

                    <span>
                        ${option}
                    </span>

                </button>

            `;

        }
    );


    const levelName =
        currentLevel === "easy"
            ? "🟢 أساسي"
            : currentLevel === "medium"
                ? "🟡 متوسط"
                : "🔴 تحدي";


    content.innerHTML = `

        <button
            class="close"
            onclick="closeQuiz()">

            ×

        </button>


        <div class="quiz-header">

            <span class="quiz-level-title">
                ${currentQuizTitle}
            </span>

            <span class="question-counter">

                ${levelName}

                <br>

                السؤال
                ${currentQuestion + 1}
                من
                ${currentQuiz.length}

            </span>

        </div>


        <div class="question-box">

            <h2>
                ${question.q}
            </h2>

        </div>


        <div class="quiz-options">

            ${options}

        </div>

    `;
}


// =====================================================
// الإجابة عن سؤال
// =====================================================

function answerQuestion(selected) {

    const question =
        currentQuiz[currentQuestion];


    const buttons =
        document.querySelectorAll(
            ".quiz-option"
        );


    buttons.forEach(
        function(button) {
            button.disabled = true;
        }
    );


    buttons.forEach(
        function(button, index) {

            if (
                index === question.answer
            ) {

                button.classList.add(
                    "correct"
                );

            }


            if (
                index === selected &&
                selected !== question.answer
            ) {

                button.classList.add(
                    "wrong"
                );

            }

        }
    );


    if (
        selected === question.answer
    ) {

        score++;

    }


    setTimeout(
        function() {

            currentQuestion++;

            showQuestion();

        },
        900
    );
}


// =====================================================
// نتيجة الاختبار
// =====================================================

function showResult() {

    const content =
        document.getElementById("quizContent");


    const percentage =
        Math.round(
            (score / currentQuiz.length) * 100
        );


    let icon;
    let message;


    if (percentage >= 90) {

        icon = "🏆";

        message =
            "ممتاز جدًا! واضح أنك تفهم وتستنتج، وليس فقط تحفظ.";

    }

    else if (percentage >= 75) {

        icon = "👏";

        message =
            "ممتاز! بقيت بعض النقاط الصغيرة وتوصل للمستوى الأعلى.";

    }

    else if (percentage >= 60) {

        icon = "💪";

        message =
            "جيد، راجع المفاهيم التي أخطأت فيها وحاول مرة أخرى.";

    }

    else {

        icon = "📚";

        message =
            "راجع الدرس بهدوء ثم أعد الاختبار. الهدف هو الفهم.";

    }


    content.innerHTML = `

        <button
            class="close"
            onclick="closeQuiz()">

            ×

        </button>


        <div class="result">

            <div class="result-icon">
                ${icon}
            </div>

            <h2>
                انتهى الاختبار
            </h2>

            <p>
                ${currentQuizTitle}
            </p>

            <div class="score">
                ${score} / ${currentQuiz.length}
            </div>

            <p class="percentage">
                ${percentage}%
            </p>

            <p>
                ${message}
            </p>


            <div class="result-buttons">

                <button
                    class="main-action"
                    onclick="restartCurrentQuiz()">

                    🔄 إعادة الاختبار

                </button>


                <button
                    class="secondary-action"
                    onclick="closeQuiz()">

                    🏠 العودة للموقع

                </button>

            </div>

        </div>

    `;
}


