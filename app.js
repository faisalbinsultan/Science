// =====================================================
// تنظيف الإجابة
// =====================================================

function normalizeArabicAnswer(text) {

    return text

        .trim()

        .toLowerCase()

        .replace(/[ًٌٍَُِّْـ]/g, "")

        .replace(/[أإآ]/g, "ا")

        .replace(/ى/g, "ي")

        .replace(/ة/g, "ه")

        .replace(/\s+/g, " ");

}


// =====================================================
// الحصول على أول حرف حقيقي
// =====================================================

function getFirstArabicLetter(text) {

    const cleaned =
        normalizeArabicAnswer(text);


    if (!cleaned) {
        return "";
    }


    return cleaned.charAt(0);
}


