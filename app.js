// المتغيرات الخاصة بالاختبار
// ==========================================

let currentQuizLevel = "easy";
let currentQuiz = [];
let currentQuestion = 0;
let score = 0;


// ==========================================
// فتح الدرس
// ==========================================

function openLesson(lessonId) {

    const lesson = lessons[lessonId];

    if (!lesson) {
        return;
    }

    const modal = document.getElementById("lessonModal");
    const content = document.getElementById("lessonContent");

    if (!modal || !content) {
        return;
    }

    content.innerHTML = `
        <div class="lesson-header">
            <div class="lesson-big-icon">${lesson.icon}</div>
            ${lesson.content}
        </div>

        <button class="main-action" onclick="closeLesson()">
            🏠 العودة للموقع
        </button>
    `;

    modal.classList.add("show");

    document.body.style.overflow = "hidden";
}


// ==========================================
// إغلاق الدرس
// ==========================================

function closeLesson() {

    const modal = document.getElementById("lessonModal");

    if (modal) {
        modal.classList.remove("show");
    }

    document.body.style.overflow = "";
}


// ==========================================
// بدء الاختبار
// ==========================================

function startQuiz(level) {

    if (!quizzes[level]) {
        level = "easy";
    }

    currentQuizLevel = level;

    // نسخ الأسئلة حتى لا تتغير البيانات الأصلية
    currentQuiz = [...quizzes[level]];

    // خلط الأسئلة
    currentQuiz.sort(() => Math.random() - 0.5);

    currentQuestion = 0;
    score = 0;

    const modal = document.getElementById("quizModal");

    if (!modal) {
        return;
    }

    modal.classList.add("show");

    document.body.style.overflow = "hidden";

    showQuestion();
}


// ==========================================
// عرض السؤال
// ==========================================

function showQuestion() {

    const content = document.getElementById("quizContent");

    if (!content) {
        return;
    }

    if (currentQuestion >= currentQuiz.length) {
        showResult();
        return;
    }

    const question = currentQuiz[currentQuestion];

    let optionsHTML = "";

    question.options.forEach(function (option, index) {

        optionsHTML += `
            <button
                class="quiz-option"
                onclick="answerQuestion(${index})">

                <span class="option-number">
                    ${index + 1}
                </span>

                <span>
                    ${option}
                </span>

            </button>
        `;
    });


    const levelName =
        currentQuizLevel === "easy"
            ? "🟢 المستوى الأساسي"
            : currentQuizLevel === "medium"
                ? "🟡 المستوى المتوسط"
                : "🔴 مستوى التحدي";


    content.innerHTML = `

        <div class="quiz-header">

            <span class="quiz-level-title">
                ${levelName}
            </span>

            <span class="question-counter">
                السؤال ${currentQuestion + 1} من ${currentQuiz.length}
            </span>

        </div>


        <div class="question-box">

            <h2>
                ${question.q}
            </h2>

        </div>


        <div class="quiz-options">

            ${optionsHTML}

        </div>

    `;
}


// ==========================================
// الإجابة على السؤال
// ==========================================

function answerQuestion(selectedAnswer) {

    const question = currentQuiz[currentQuestion];

    const buttons =
        document.querySelectorAll(".quiz-option");

    buttons.forEach(function (button) {
        button.disabled = true;
    });


    buttons.forEach(function (button, index) {

        if (index === question.answer) {
            button.classList.add("correct");
        }

        if (
            index === selectedAnswer &&
            selectedAnswer !== question.answer
        ) {
            button.classList.add("wrong");
        }

    });


    if (selectedAnswer === question.answer) {
        score++;
    }


    setTimeout(function () {

        currentQuestion++;

        showQuestion();

    }, 900);
}


// ==========================================
// نتيجة الاختبار
// ==========================================

function showResult() {

    const content = document.getElementById("quizContent");

    if (!content) {
        return;
    }

    const percentage =
        Math.round((score / currentQuiz.length) * 100);


    let message = "";
    let icon = "";


    if (percentage >= 90) {

        icon = "🏆";

        message =
            "ممتاز جدًا! واضح أنك فاهم الدرس وليس فقط حافظه.";

    } else if (percentage >= 75) {

        icon = "👏";

        message =
            "أحسنت! مستواك ممتاز، راجع الأخطاء البسيطة.";

    } else if (percentage >= 60) {

        icon = "💪";

        message =
            "جيد! تحتاج إلى مراجعة بعض المفاهيم ثم إعادة الاختبار.";

    } else {

        icon = "📚";

        message =
            "لا تستعجل! راجع الدروس وحاول مرة أخرى.";

    }


    content.innerHTML = `

        <div class="result">

            <div class="result-icon">
                ${icon}
            </div>

            <h2>
                انتهى الاختبار
            </h2>

            <div class="score">
                ${score} / ${currentQuiz.length}
            </div>

            <p class="percentage">
                ${percentage}%
            </p>

            <p>
                ${message}
            </p>


            <div class="result-buttons">

                <button
                    class="main-action"
                    onclick="startQuiz('${currentQuizLevel}')">

                    🔄 أعد الاختبار

                </button>


                <button
                    class="secondary-action"
                    onclick="closeQuiz()">

                    🏠 العودة للموقع

                </button>

            </div>

        </div>

    `;
}


// ==========================================
// إغلاق الاختبار
// ==========================================

function closeQuiz() {

    const modal =
        document.getElementById("quizModal");

    if (modal) {
        modal.classList.remove("show");
    }

    document.body.style.overflow = "";
}


