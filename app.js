// =====================================================
// تنظيف النص العربي
// =====================================================

function normalizeArabicAnswer(text) {

    return String(text || "")

        .trim()

        .toLowerCase()

        .replace(
            /[ًٌٍَُِّْـ]/g,
            ""
        )

        .replace(
            /[أإآ]/g,
            "ا"
        )

        .replace(
            /ى/g,
            "ي"
        )

        .replace(
            /ة/g,
            "ه"
        )

        .replace(
            /\s+/g,
            " "

        );

}


// =====================================================
// إزالة ال التعريف
// =====================================================

function removeArabicArticle(text) {

    let value =
        normalizeArabicAnswer(
            text
        );


    if (
        value.startsWith("ال") &&
        value.length > 2
    ) {

        value =
            value.substring(2);

    }


    return value;

}


// =====================================================
// فحص الإجابة
// =====================================================

function submitLettersAnswer() {

    const input =
        document.getElementById(
            "lettersAnswerInput"
        );


    const message =
        document.getElementById(
            "lettersAnswerMessage"
        );


    if (
        !input ||
        !message
    ) {

        return;

    }


    const userAnswer =
        input.value.trim();


    if (!userAnswer) {

        message.innerHTML =
            "⚠️ اكتب إجابة أولًا.";


        message.className =
            "letters-answer-message wrong";


        return;

    }


    const index =
        lettersGameSelectedIndex;


    const cell =
        lettersGameBoard[index];


    if (!cell) {

        return;

    }


    const question =
        lettersGameQuestions[
            cell.letter
        ];


    if (!question) {

        return;

    }


    const normalizedUserAnswer =
        normalizeArabicAnswer(
            userAnswer
        );


    const acceptedAnswers =
        question.answers.map(
            function(answer) {

                return normalizeArabicAnswer(
                    answer
                );

            }
        );


    const isCorrect =
        acceptedAnswers.some(
            function(answer) {

                return (
                    normalizedUserAnswer ===
                    answer
                );

            }
        );


    // =============================================
    // إجابة صحيحة
    // =============================================

    if (isCorrect) {

        message.innerHTML =
            "🎉 إجابة صحيحة! حصل الفريق على الخانة.";


        message.className =
            "letters-answer-message correct";


        cell.owner =
            lettersCurrentTeam;


        setTimeout(
            function() {

                const winningTeam =
                    checkLettersWinner(
                        lettersCurrentTeam
                    );


                if (winningTeam) {

                    lettersGameWinner =
                        winningTeam;

                }

                else {

                    lettersCurrentTeam =
                        lettersCurrentTeam === "blue"
                            ? "red"
                            : "blue";

                }


                lettersGameSelectedIndex =
                    null;


                renderLettersGame();

            },
            900
        );

    }


    // =============================================
    // إجابة خاطئة
    // =============================================

    else {

        message.innerHTML = `

            ❌ ليست الإجابة الصحيحة.

            <br><br>

            🔄 ينتقل الدور للفريق الآخر.

        `;


        message.className =
            "letters-answer-message wrong";


        setTimeout(
            function() {

                lettersCurrentTeam =
                    lettersCurrentTeam === "blue"
                        ? "red"
                        : "blue";


                lettersGameSelectedIndex =
                    null;


                renderLettersGame();

            },
            1200
        );

    }

}


// =====================================================
// فحص الفائز
// =====================================================

function checkLettersWinner(team) {

    const size =
        5;


    const visited =
        new Set();


    const queue =
        [];


    // =============================================
    // الفريق الأزرق
    // من اليسار إلى اليمين
    // =============================================

    if (team === "blue") {

        for (
            let row = 0;
            row < size;
            row++
        ) {

            const index =
                row * size;


            if (
                lettersGameBoard[index].owner ===
                "blue"
            ) {

                queue.push(
                    index
                );


                visited.add(
                    index
                );

            }

        }

    }


    // =============================================
    // الفريق الأحمر
    // من الأعلى إلى الأسفل
    // =============================================

    else {

        for (
            let column = 0;
            column < size;
            column++
        ) {

            const index =
                column;


            if (
                lettersGameBoard[index].owner ===
                "red"
            ) {

                queue.push(
                    index
                );


                visited.add(
                    index
                );

            }

        }

    }


    while (
        queue.length > 0
    ) {

        const current =
            queue.shift();


        const row =
            Math.floor(
                current / size
            );


        const column =
            current % size;


        if (
            team === "blue" &&
            column === size - 1
        ) {

            return "blue";

        }


        if (
            team === "red" &&
            row === size - 1
        ) {

            return "red";

        }


        const neighbors = [

            [row - 1, column],

            [row + 1, column],

            [row, column - 1],

            [row, column + 1]

        ];


        neighbors.forEach(
            function(position) {

                const newRow =
                    position[0];


                const newColumn =
                    position[1];


                if (

                    newRow < 0 ||

                    newRow >= size ||

                    newColumn < 0 ||

                    newColumn >= size

                ) {

                    return;

                }


                const nextIndex =
                    newRow * size +
                    newColumn;


                if (
                    visited.has(
                        nextIndex
                    )
                ) {

                    return;

                }


                if (
                    lettersGameBoard[
                        nextIndex
                    ].owner !== team
                ) {

                    return;

                }


                visited.add(
                    nextIndex
                );


                queue.push(
                    nextIndex
                );

            }
        );

    }


    return null;

}


