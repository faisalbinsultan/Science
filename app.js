// الاختبارات
// ======================================================

let currentQuiz = [];
let currentQuestion = 0;
let score = 0;
let selectedLevel = "hard";


function startQuiz(level) {

    selectedLevel = level;

    currentQuiz = [...questionBank[level]];

    // خلط الأسئلة
    currentQuiz.sort(() => Math.random() - 0.5);

    currentQuestion = 0;
    score = 0;

    document.getElementById("quizModal").classList.add("show");

    showQuestion();
}


function showQuestion() {

    const content = document.getElementById("quizContent");

    if (currentQuestion >= currentQuiz.length) {
        showResult();
        return;
    }

    const question = currentQuiz[currentQuestion];

    let optionsHTML = "";

    question.options.forEach(function(option, index) {

        optionsHTML += `
            <button class="quiz-option"
                    onclick="answerQuestion(${index})">
                <span>${String.fromCharCode(65 + index)}</span>
                ${option}
            </button>
        `;

    });


    content.innerHTML = `

        <div class="quiz-top">

            <span>
                السؤال ${currentQuestion + 1}
                من ${currentQuiz.length}
            </span>

            <span>
                الدرجة: ${score}
            </span>

        </div>

        <div class="quiz-progress">

            <div style="width:
                ${((currentQuestion) / currentQuiz.length) * 100}%">
            </div>

        </div>

        <h2 class="question">
            ${question.q}
        </h2>

        <div class="quiz-options">
            ${optionsHTML}
        </div>

    `;
}


function answerQuestion(selected) {

    const question = currentQuiz[currentQuestion];

    const buttons = document.querySelectorAll(".quiz-option");

    buttons.forEach(function(button) {
        button.disabled = true;
    });


    if (selected === question.answer) {

        score++;

        buttons[selected].classList.add("correct");

    } else {

        buttons[selected].classList.add("wrong");

        buttons[question.answer].classList.add("correct");

    }


    setTimeout(function() {

        currentQuestion++;

        showQuestion();

    }, 900);
}


// ======================================================
// نتيجة الاختبار
// ======================================================

function showResult() {

    const content = document.getElementById("quizContent");

    const percentage =
        Math.round((score / currentQuiz.length) * 100);


    let message = "";

    if (percentage >= 90) {

        message = "🔥 ممتاز جدًا! واضح أنك فاهم الدرس وليس فقط حافظه.";

    } else if (percentage >= 70) {

        message = "👏 ممتاز! لكن ما زال بإمكانك رفع مستواك.";

    } else if (percentage >= 50) {

        message = "💪 جيد، راجع النقاط التي أخطأت فيها ثم حاول مرة أخرى.";

    } else {

        message = "📚 تحتاج مراجعة أكثر. لا تعتمد على الحفظ فقط.";

    }


    content.innerHTML = `

        <div class="result">

            <div class="result-icon">
                ${percentage >= 70 ? "🏆" : "📚"}
            </div>

            <h2>انتهى الاختبار</h2>

            <div class="score">
                ${score} / ${currentQuiz.length}
            </div>

            <p class="percentage">
                ${percentage}%
            </p>

            <p>
                ${message}
            </p>

            <div class="result-buttons">

                <button class="main-action"
                        onclick="startQuiz('${selectedLevel}')">
                    🔄 أعد الاختبار
                </button>

                <button class="secondary-action"
                        onclick="closeQuiz()">
                    🏠 العودة للموقع
                </button>

            </div>

        </div>

    `;
}


function closeQuiz() {

    document.getElementById("quizModal").classList.remove("show");

}


